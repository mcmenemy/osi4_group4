// Provisional benchmark from the team's draft paper, "What can carry a mind? A
// cross-framework benchmark of device-side substrates for biohybrid neural
// interfaces" (v0.1). Scores are judgment calls, labeled as such on the page.

export type FrameworkKey =
  | 'functionalism'
  | 'global_workspace'
  | 'iit'
  | 'active_inference'
  | 'em_field'
  | 'orch_or'

export interface Framework {
  key: FrameworkKey
  name: string
  short: string
  summary: string
}

export interface Substrate {
  key: string
  name: string
  summary: string
  scores: Record<FrameworkKey, number>
  reasons: Record<FrameworkKey, string>
  maintainability: number
  maintainabilityReason?: string
  // Functionalism's 3 is conditional on functional equivalence being achieved.
  conditional?: boolean
}

